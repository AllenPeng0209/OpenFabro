async (page, options = {}) =>{
  const origin=options.origin||'http://127.0.0.1:8770',previous=await page.evaluate(()=>location.hash.slice(1));
  const p=await(await page.request.post(origin+'/api/workbench/projects',{data:{title:'Native schematic editing acceptance',example:true}})).json();
  try{
    await page.setViewportSize({width:1440,height:1000});
    await page.goto(origin+'/?schematic-qa='+Date.now()+'#'+p.id);
    await page.getByRole('tab',{name:'Schematic',exact:true}).click();
    await page.waitForSelector('.canvas-component[data-ref="R1"]');
    await page.waitForSelector('.native-symbol-graphics',{timeout:10000});
    if(!await page.locator('.native-symbol-graphics').count())throw new Error('The schematic does not yet render actual KiCad symbol geometry');
    await page.locator('.canvas-component[data-ref="R1"]').click();
    const glyph=page.locator('.canvas-component[data-ref="R1"] .native-symbol-graphics');
    const before=await glyph.boundingBox();
    const saved=page.waitForResponse(r=>r.url().endsWith('/design')&&r.request().method()==='PUT'&&r.status()===200);
    await page.locator('#rotatePart').click();await saved;
    let state=(await(await page.request.get(origin+'/api/projects/'+p.id)).json()).state;
    if(state.spec.editor.rotations.R1!==270)throw new Error('Schematic rotation was not saved as schematic presentation');
    if(state.spec.components.find(c=>c.ref==='R1').placement.rotation!==0)throw new Error('Schematic rotation incorrectly changed PCB placement');
    await page.waitForSelector('.native-symbol-graphics');
    const after=await glyph.boundingBox();
    if(!(before.height>before.width&&after.width>after.height))throw new Error('The native resistor graphics did not visibly rotate');
    const checks=['Native KiCad symbols render in the web schematic','Rotation changes schematic presentation and preserves PCB pose','Native glyph visibly rotates with the saved schematic angle'];
    await page.keyboard.press('0');const framed=await glyph.boundingBox();
    const valueSaved=page.waitForResponse(r=>r.url().endsWith('/design')&&r.request().method()==='PUT'&&r.status()===200);
    await page.locator('[data-property="value"]').fill('4.7k');await page.locator('[data-property="value"]').press('Tab');await valueSaved;
    await page.waitForFunction(()=>[...document.querySelectorAll('[data-ref="R1"] text')].some(el=>el.textContent==='4.7k'));
    const retained=await glyph.boundingBox();
    if(Math.abs(retained.width/framed.width-1)>.03||Math.abs(retained.x-framed.x)>3)throw new Error('Editing reset the native schematic camera');
    checks.push('Zoom and framing survive an edit and native schematic regeneration');
    state=(await(await page.request.get(origin+'/api/projects/'+p.id)).json()).state;
    const wiring=structuredClone(state.spec);
    wiring.components.push({ref:'R4',value:'10k',symbol:'Device:R',footprint:'Resistor_SMD:R_0603_1608Metric',placement:{x_mm:20,y_mm:12,rotation:0}});
    wiring.editor.positions.R4=[700,620];
    const update=await page.request.put(`${origin}/api/workbench/projects/${p.id}/design`,{data:{base_version:state.workbench.version,spec:wiring}});
    if(!update.ok())throw new Error(await update.text());
    await page.reload();await page.waitForSelector('.native-symbol-graphics');
    await page.locator('#wireButton').click();
    await page.locator('[data-pinref="R4.1"]').click();
    const wired=page.waitForResponse(r=>r.url().endsWith('/design')&&r.request().method()==='PUT'&&r.status()===200);
    await page.locator('[data-pinref="J2.3"]').click();await wired;
    let current=(await(await page.request.get(origin+'/api/projects/'+p.id)).json()).state;
    if(!current.spec.nets.some(n=>n.pins.includes('R4.1')&&n.pins.includes('J2.3')))throw new Error('Direct wire did not create a canonical electrical connection');
    if(current.spec.components.find(c=>c.ref==='J2').no_connect?.includes('3'))throw new Error('Wiring left the connected pin marked no-connect');
    checks.push('Pin-to-pin gesture persists canonical nets and removes no-connect');
    await page.waitForSelector('.native-schematic-wire',{state:'attached'});
    checks.push('Pin connections render native solid wire segments');
    await page.locator('#wireButton').click();
    const hit=await page.locator('[data-wire-route="0"]').first().evaluate(path=>{const p=path.getPointAtLength(path.getTotalLength()/2).matrixTransform(path.getScreenCTM());return{x:p.x,y:p.y};});
    await page.mouse.click(hit.x,hit.y);await page.locator('.wire-segment-handle').first().waitFor();
    const handle=page.locator('.wire-segment-handle').first();await handle.hover();const box=await handle.boundingBox(),direction=await handle.evaluate(el=>el.style.cursor),beforeNets=JSON.stringify(current.spec.nets),beforeComponents=JSON.stringify(current.spec.components);
    const reshaped=page.waitForResponse(r=>r.url().endsWith('/design')&&r.request().method()==='PUT'&&r.ok());
    await page.mouse.move(box.x+box.width/2,box.y+box.height/2);await page.mouse.down();await page.mouse.move(box.x+box.width/2+(direction==='ew-resize'?-15:0),box.y+box.height/2+(direction==='ns-resize'?-15:0),{steps:8});await page.mouse.up();await reshaped;
    current=(await(await page.request.get(origin+'/api/projects/'+p.id)).json()).state;
    if(!current.spec.editor.connection_guides[0].waypoints?.length)throw new Error('Dragging a native wire did not save its bends');
    if(JSON.stringify(current.spec.nets)!==beforeNets||JSON.stringify(current.spec.components)!==beforeComponents)throw new Error('Moving a schematic wire changed electrical or PCB data');
    const regenerated=await(await page.request.post(origin+'/api/workbench/schematic-view',{data:current.spec})).json();
    await page.waitForSelector(`svg[data-schematic-hash="${regenerated.fingerprint}"] .native-schematic-wire`,{state:'attached'});
    if(regenerated.routes[0].status!=='routed')throw new Error('The moved wire could not be exported safely');
    checks.push('Dragging a native wire segment persists bends without changing the netlist or PCB');
    await page.getByRole('button',{name:'Zoom to fit',exact:true}).click();
    await page.locator('#wireButton').click();
    await page.waitForSelector('.native-symbol-graphics');
    await page.locator('[data-pinref="R1.1"]').click();
    await page.locator('[data-pinref="R2.1"]').click();
    await page.locator('#mergeNetDialog').waitFor({state:'visible'});
    current=(await(await page.request.get(origin+'/api/projects/'+p.id)).json()).state;
    if(!current.spec.nets.some(n=>n.name==='CC2'))throw new Error('Different electrical nets merged before user confirmation');
    const merged=page.waitForResponse(r=>r.url().endsWith('/design')&&r.request().method()==='PUT'&&r.status()===200);
    await page.locator('#confirmNetMerge').click();await merged;
    current=(await(await page.request.get(origin+'/api/projects/'+p.id)).json()).state;
    if(!current.spec.nets.some(n=>n.pins.includes('R1.1')&&n.pins.includes('R2.1')))throw new Error('Confirmed wire merge was not saved');
    checks.push('Merging separate nets waits for explicit confirmation');
    current.spec.components.filter(c=>['R1','R2'].includes(c.ref)).forEach(c=>c.sheet='Power');
    await page.request.put(`${origin}/api/workbench/projects/${p.id}/design`,{data:{base_version:current.workbench.version,spec:current.spec}});
    await page.reload();await page.waitForSelector('[data-sheet-target="Power"]');
    if(await page.locator('.canvas-component[data-ref="R1"]').count())throw new Error('Child sheet symbols leaked into the root sheet');
    await page.locator('[data-sheet-target="Power"]').dblclick();
    await page.waitForSelector('.canvas-component[data-ref="R1"] .native-symbol-graphics',{timeout:5000});
    if(await page.locator('.canvas-component[data-ref="U1"]').count())throw new Error('Root sheet symbols leaked into the child sheet');
    await page.locator('#schematicSheet').selectOption('');
    await page.waitForSelector('[data-sheet-target="Power"]');
    checks.push('Actual hierarchical sheets open and return without mixing page symbols');
    return{checks};
  }finally{
    await page.goto(origin+'/?schematic-qa-finished='+Date.now()+(previous&&previous!=='projects'?'#'+previous:''));
    await page.request.delete(origin+'/api/projects/'+p.id);
  }
}
